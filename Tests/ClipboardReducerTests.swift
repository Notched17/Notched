import Foundation
import Testing
@testable import Notched

/// Clipboard history's rules (#45).
@Suite("ClipboardReducer")
struct ClipboardReducerTests {
    let t0 = Date(timeIntervalSinceReferenceDate: 100_000)

    private func candidate(_ text: String, kind: ClipboardKind = .text) -> ClipboardCandidate {
        ClipboardCandidate(kind: kind, text: text, contentHash: "hash-\(kind.rawValue)-\(text)")
    }

    private func capture(_ text: String, kind: ClipboardKind = .text, types: [String] = ["public.utf8-plain-text"],
                         app: String? = "com.apple.Safari", id: UUID = UUID()) -> ClipboardCapture {
        ClipboardCapture(typeIdentifiers: types, sourceBundleID: app, sourceName: "Safari", candidate: candidate(text, kind: kind), newID: id)
    }

    /// A reducer that has seen its first tick.
    private func running(limit: Int = 200) -> ClipboardReducer {
        var sut = ClipboardReducer()
        _ = sut.reduce(.configure(.init(limit: limit)), now: t0)
        _ = sut.reduce(.tick(changeCount: 1), now: t0)
        return sut
    }

    private func texts(_ sut: ClipboardReducer) -> [String] { sut.state.entries.map(\.text) }

    @Test("The first change count is silent, a changed one asks for a read, an unchanged one does nothing")
    func ticks() {
        var sut = ClipboardReducer()
        #expect(sut.reduce(.tick(changeCount: 5), now: t0).isEmpty)
        #expect(sut.reduce(.tick(changeCount: 5), now: t0).isEmpty)
        #expect(sut.reduce(.tick(changeCount: 6), now: t0) == [.read(changeCount: 6)])
        #expect(sut.reduce(.tick(changeCount: 6), now: t0).isEmpty)
    }

    @Test("A copy becomes the newest entry and is saved")
    func recordsCopy() {
        var sut = running()
        let id = UUID()
        let effects = sut.reduce(.captured(capture("hello", id: id)), now: t0)
        #expect(texts(sut) == ["hello"])
        #expect(sut.state.entries[0].id == id)
        #expect(sut.state.entries[0].sourceName == "Safari")
        #expect(effects == [.persist(sut.state.entries)])
    }

    @Test("Newest first")
    func ordering() {
        var sut = running()
        _ = sut.reduce(.captured(capture("one")), now: t0)
        _ = sut.reduce(.captured(capture("two")), now: t0 + 1)
        #expect(texts(sut) == ["two", "one"])
    }

    @Test("Copying the same thing again moves it to the top without a second entry, and keeps its pin")
    func dedupe() {
        var sut = running()
        _ = sut.reduce(.captured(capture("one")), now: t0)
        let pinned = sut.state.entries[0].id
        _ = sut.reduce(.togglePin(pinned), now: t0)
        _ = sut.reduce(.captured(capture("two")), now: t0 + 1)
        _ = sut.reduce(.captured(capture("one", app: "com.apple.Notes")), now: t0 + 2)
        #expect(texts(sut) == ["one", "two"])
        #expect(sut.state.entries[0].id == pinned)
        #expect(sut.state.entries[0].isPinned)
        #expect(sut.state.entries[0].createdAt == t0 + 2)
        #expect(sut.state.entries[0].sourceBundleID == "com.apple.Notes")
    }

    @Test("Text and a link with the same characters are different entries")
    func kindsAreDistinct() {
        var sut = running()
        _ = sut.reduce(.captured(ClipboardCapture(typeIdentifiers: [], sourceBundleID: nil, sourceName: nil,
                                                  candidate: ClipboardCandidate(kind: .text, text: "x", contentHash: "same"), newID: UUID())), now: t0)
        _ = sut.reduce(.captured(ClipboardCapture(typeIdentifiers: [], sourceBundleID: nil, sourceName: nil,
                                                  candidate: ClipboardCandidate(kind: .url, text: "x", contentHash: "same"), newID: UUID())), now: t0)
        #expect(sut.state.entries.count == 2)
    }

    @Test("Private items are never kept", arguments: [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ])
    func skipsPrivateTypes(type: String) {
        var sut = running()
        let effects = sut.reduce(.captured(capture("hunter2", types: ["public.utf8-plain-text", type])), now: t0)
        #expect(effects.isEmpty)
        #expect(sut.state.entries.isEmpty)
    }

    @Test("Copies from an excluded app are never kept, and the list can change")
    func skipsExcludedApps() {
        var sut = ClipboardReducer()
        _ = sut.reduce(.configure(.init(limit: 200, excludedApps: ["com.bitwarden.desktop"])), now: t0)
        _ = sut.reduce(.tick(changeCount: 1), now: t0)
        #expect(sut.reduce(.captured(capture("secret", app: "com.bitwarden.desktop")), now: t0).isEmpty)
        #expect(sut.state.entries.isEmpty)
        _ = sut.reduce(.configure(.init(limit: 200, excludedApps: [])), now: t0)
        _ = sut.reduce(.captured(capture("secret", app: "com.bitwarden.desktop")), now: t0)
        #expect(texts(sut) == ["secret"])
    }

    @Test("The default exclusions cover the common password managers")
    func defaultExclusions() {
        let defaults = ClipboardReducer.Config().excludedApps
        #expect(defaults.contains("com.1password.1password"))
        #expect(defaults.contains("com.apple.keychainaccess"))
        #expect(defaults.contains("org.keepassxc.keepassxc"))
    }

    @Test("A read that found nothing usable records nothing")
    func nothingUsable() {
        var sut = running()
        let empty = ClipboardCapture(typeIdentifiers: [], sourceBundleID: nil, sourceName: nil, candidate: nil, newID: UUID())
        #expect(sut.reduce(.captured(empty), now: t0).isEmpty)
    }

    @Test("Our own copy-back is not recorded again")
    func ownWriteIsIgnored() {
        var sut = running()
        _ = sut.reduce(.captured(capture("one")), now: t0)
        let id = sut.state.entries[0].id
        #expect(sut.reduce(.copyBack(id), now: t0) == [.writeToPasteboard(sut.state.entries[0])])
        _ = sut.reduce(.wrote(changeCount: 9), now: t0)
        #expect(sut.reduce(.tick(changeCount: 9), now: t0).isEmpty)
        #expect(sut.reduce(.tick(changeCount: 10), now: t0) == [.read(changeCount: 10)])
    }

    @Test("Copying back an unknown item does nothing")
    func copyBackUnknown() {
        var sut = running()
        #expect(sut.reduce(.copyBack(UUID()), now: t0).isEmpty)
    }

    @Test("Past the length the oldest unpinned items go; pinned ones stay and don't count")
    func eviction() {
        var sut = running(limit: 3)
        for index in 1...3 { _ = sut.reduce(.captured(capture("item\(index)")), now: t0 + Double(index)) }
        let oldest = sut.state.entries.last!.id
        _ = sut.reduce(.togglePin(oldest), now: t0)
        for index in 4...8 { _ = sut.reduce(.captured(capture("item\(index)")), now: t0 + Double(index)) }
        #expect(texts(sut) == ["item8", "item7", "item6", "item1"])
        #expect(sut.state.entries.filter { !$0.isPinned }.count == 3)
    }

    @Test("A shorter length trims straight away and saves; a longer one does nothing")
    func lengthChange() {
        var sut = running(limit: 50)
        for index in 1...10 { _ = sut.reduce(.captured(capture("item\(index)")), now: t0 + Double(index)) }
        let effects = sut.reduce(.configure(.init(limit: 4)), now: t0)
        #expect(sut.state.entries.count == 4)
        #expect(effects == [.persist(sut.state.entries)])
        #expect(sut.reduce(.configure(.init(limit: 100)), now: t0).isEmpty)
    }

    @Test("Unpinning an item over the length drops the oldest")
    func unpinTrims() {
        var sut = running(limit: 2)
        _ = sut.reduce(.captured(capture("a")), now: t0)
        let a = sut.state.entries[0].id
        _ = sut.reduce(.togglePin(a), now: t0)
        _ = sut.reduce(.captured(capture("b")), now: t0 + 1)
        _ = sut.reduce(.captured(capture("c")), now: t0 + 2)
        #expect(sut.state.entries.count == 3)
        _ = sut.reduce(.togglePin(a), now: t0)
        #expect(texts(sut) == ["c", "b"])
    }

    @Test("Deleting an image removes its file only when nothing else uses it")
    func imageFiles() {
        var sut = running()
        _ = sut.reduce(.captured(capture("Image 1 × 1", kind: .image)), now: t0)
        let image = sut.state.entries[0].id
        #expect(sut.reduce(.delete(image), now: t0) == [.persist([]), .deleteImage(contentHash: "hash-image-Image 1 × 1")])
        #expect(sut.reduce(.delete(image), now: t0).isEmpty)
    }

    @Test("Eviction of an image deletes its file")
    func evictedImageFile() {
        var sut = running(limit: 1)
        _ = sut.reduce(.captured(capture("Image 2 × 2", kind: .image)), now: t0)
        let effects = sut.reduce(.captured(capture("later")), now: t0 + 1)
        #expect(effects.contains(.deleteImage(contentHash: "hash-image-Image 2 × 2")))
    }

    @Test("Clear keeps pinned items; clearing everything doesn't")
    func clearing() {
        var sut = running()
        _ = sut.reduce(.captured(capture("keep")), now: t0)
        _ = sut.reduce(.togglePin(sut.state.entries[0].id), now: t0)
        _ = sut.reduce(.captured(capture("drop")), now: t0 + 1)
        _ = sut.reduce(.clear(includingPinned: false), now: t0)
        #expect(texts(sut) == ["keep"])
        _ = sut.reduce(.clear(includingPinned: true), now: t0)
        #expect(sut.state.entries.isEmpty)
        #expect(sut.reduce(.clear(includingPinned: true), now: t0).isEmpty)
    }

    @Test("Quitting clears only when asked to")
    func quit() {
        var sut = running()
        _ = sut.reduce(.captured(capture("one")), now: t0)
        #expect(sut.reduce(.quit, now: t0).isEmpty)
        #expect(texts(sut) == ["one"])
        _ = sut.reduce(.configure(.init(limit: 200, clearOnQuit: true)), now: t0)
        #expect(sut.reduce(.quit, now: t0) == [.persist([])])
        #expect(sut.state.entries.isEmpty)
    }

    @Test("Loading a long saved history trims it")
    func loadTrims() {
        var sut = ClipboardReducer()
        _ = sut.reduce(.configure(.init(limit: 2)), now: t0)
        let saved = (1...5).map { ClipboardEntry(id: UUID(), kind: .text, text: "t\($0)", contentHash: "h\($0)", createdAt: t0) }
        let effects = sut.reduce(.loaded(saved), now: t0)
        #expect(sut.state.entries.count == 2)
        #expect(effects == [.persist(sut.state.entries)])
    }

    @Test("Random events keep the limit, unique content and pins")
    func fuzz() {
        var generator = SystemRandomNumberGenerator()
        var sut = running(limit: 5)
        var count = 1
        for step in 0..<800 {
            switch Int.random(in: 0..<10, using: &generator) {
            case 0, 1, 2, 3:
                count += 1
                _ = sut.reduce(.tick(changeCount: count), now: t0 + Double(step))
                _ = sut.reduce(.captured(capture("t\(Int.random(in: 0..<12, using: &generator))")), now: t0 + Double(step))
            case 4:
                if let entry = sut.state.entries.randomElement(using: &generator) { _ = sut.reduce(.togglePin(entry.id), now: t0) }
            case 5:
                if let entry = sut.state.entries.randomElement(using: &generator) { _ = sut.reduce(.delete(entry.id), now: t0) }
            case 6:
                _ = sut.reduce(.configure(.init(limit: Int.random(in: 1...6, using: &generator))), now: t0)
            case 7:
                _ = sut.reduce(.clear(includingPinned: Bool.random(using: &generator)), now: t0)
            default:
                if let entry = sut.state.entries.randomElement(using: &generator) { _ = sut.reduce(.copyBack(entry.id), now: t0) }
            }
            let entries = sut.state.entries
            #expect(entries.filter { !$0.isPinned }.count <= sut.state.config.limit)
            #expect(Set(entries.map(\.contentHash)).count == entries.count)
            #expect(Set(entries.map(\.id)).count == entries.count)
        }
    }
}
